/**
 * The shape every locale must match: the same keys, but any string as a value.
 *
 * `en` is `as const` so key autocompletion works, which also makes every value
 * a literal type — `typeof en` would require Hindi to spell "Gita" in English.
 * Widening the leaves keeps the structural check that matters (a missing or
 * misspelled key is still an error) and drops the one that cannot hold.
 */
type Widen<T> = T extends string ? string : { [K in keyof T]: Widen<T[K]> };

export type TranslationSchema = Widen<typeof en>;
